import Foundation

public enum TerminalLaunch {
    /// One Tab Config per preset, so launching two presets in a row cannot run the wrong one.
    public static func warpTabConfigName(_ plan: LaunchPlan) -> String { "hangar_\(plan.stem)" }

    /// Removes the Tab Configs this app wrote under its first name (`agent_launcher.toml`,
    /// `agent_launcher_<preset>.toml`). Nothing else in the folder is touched.
    public static func removeLegacyTabConfigs(in folder: URL) {
        guard let names = try? FileManager.default.contentsOfDirectory(atPath: folder.path) else { return }
        for name in names where name == "agent_launcher.toml" || (name.hasPrefix("agent_launcher_") && name.hasSuffix(".toml")) {
            try? FileManager.default.removeItem(at: folder.appending(path: name))
        }
    }

    public static func warpTabConfigURL(_ plan: LaunchPlan) -> URL {
        plan.paths.warpTabConfigs.appending(path: "\(warpTabConfigName(plan)).toml")
    }

    /// Warp's documented way to open a tab that runs a command: a Tab Config opened by
    /// `warp://tab_config/<name>` (https://docs.warp.dev/terminal/windows/tab-configs).
    public static func warpTabConfig(_ plan: LaunchPlan) -> String {
        """
        # Generated by Hangar at every launch: edits here are overwritten.
        name = \(TOML.string("Hangar · \(plan.preset.name)"))

        [[panes]]
        id = "main"
        type = "terminal"
        directory = \(TOML.string(plan.directory))
        commands = [\(TOML.string(Shell.quote(plan.scriptURL.path)))]

        """
    }

    /// The process to run (argv). For Warp the Tab Config must be written first.
    public static func command(_ settings: TerminalSettings, plan: LaunchPlan) -> [String] {
        switch settings.kind {
        case .terminal:
            // opening a .command file needs no Automation permission, unlike `do script`
            return ["/usr/bin/open", "-a", "Terminal", plan.scriptURL.path]
        case .warp:
            return ["/usr/bin/open", "warp://tab_config/\(warpTabConfigName(plan))?new_window=true"]
        case .custom:
            // one pass: a placeholder inside a substituted value is never expanded again
            let line = settings.customCommand.components(separatedBy: "{script}")
                .map { $0.replacingOccurrences(of: "{dir}", with: Shell.quote(plan.directory)) }
                .joined(separator: Shell.quote(plan.scriptURL.path))
            return ["/bin/sh", "-c", line]
        }
    }

    public struct Failure: Error, LocalizedError {
        public let status: Int32
        public let output: String
        public var errorDescription: String? {
            output.isEmpty
                ? String(localized: "The terminal command exited with code \(status).", bundle: .module)
                : String(localized: "The terminal command exited with code \(status): \(output)", bundle: .module)
        }
    }

    /// Writes the generated files and opens the terminal. Blocks until the opener exits.
    public static func run(_ plan: LaunchPlan, settings: TerminalSettings) throws {
        try plan.writeFiles()
        if settings.kind == .warp {
            try FileManager.default.createDirectory(at: plan.paths.warpTabConfigs, withIntermediateDirectories: true)
            try Data(warpTabConfig(plan).utf8).write(to: warpTabConfigURL(plan), options: .atomic)
        }
        let argv = command(settings, plan: plan)
        let process = Process()
        process.executableURL = URL(fileURLWithPath: argv[0])
        process.arguments = Array(argv.dropFirst())
        // a file, not a pipe: a terminal started by a custom command may keep a pipe open forever
        let log = FileManager.default.temporaryDirectory.appending(path: "hangar-\(UUID().uuidString).log")
        FileManager.default.createFile(atPath: log.path, contents: nil)
        let handle = try FileHandle(forWritingTo: log)
        defer {
            try? handle.close()
            try? FileManager.default.removeItem(at: log)
        }
        process.standardOutput = handle
        process.standardError = handle
        try process.run()
        process.waitUntilExit()
        guard process.terminationStatus == 0 else {
            let output = (try? String(contentsOf: log, encoding: .utf8)) ?? ""
            throw Failure(status: process.terminationStatus, output: output.trimmingCharacters(in: .whitespacesAndNewlines))
        }
    }
}
