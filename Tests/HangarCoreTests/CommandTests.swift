@Suite struct ShellTests {
    @Test func quotesOnlyWhatNeedsIt() {
        #expect(Shell.quote("qwen3-coder-30b") == "qwen3-coder-30b")
        #expect(Shell.quote("/a b") == "'/a b'")
        #expect(Shell.quote("it's") == "'it'\\''s'")
        #expect(Shell.quote("") == "''")
        #expect(Shell.quote("$(rm)") == "'$(rm)'")
        #expect(Shell.quote("=ls") == "'=ls'")         // zsh would expand it to /bin/ls
        #expect(Shell.quote("a=b") == "a=b")
    }
}

