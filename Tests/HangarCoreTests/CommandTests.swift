@Suite struct PreviewTests {
    @Test func previewMasksTheKeyBehindItsFile() throws {
        for tool in Tool.allCases {
            let plan = try plan(tool)
            #expect(!plan.preview.contains(secret))
            #expect(plan.preview.hasPrefix("cd '/tmp/work dir' && \\\n"))
        }
        let codex = try plan(.codex).preview
        #expect(codex.contains("auth={command=\"cat\", args=[\""))
        #expect(codex.contains("\(unset) codex \\\n  -c "))
        #expect(codex.hasSuffix(" \\\n  -m qwen3-coder-30b"))
    }

    @Test func previewRunsExactlyTheScriptsCommand() throws {
        for tool in Tool.allCases {
            for account in [nil, "lavoro"] as [String?] {
                var preset = try plan(tool, extra: "--resume").preset
                if account != nil || tool.spec.modes == [.account] {
                    preset.mode = .account
                    preset.account = account
                }
                let plan = LaunchPlan(preset: preset, directory: "/tmp/work dir", paths: try plan(tool).paths)
                let previewCommand = plan.preview.components(separatedBy: " && \\\n")[1]
                    .replacingOccurrences(of: " \\\n  ", with: " ")
                // the script runs the same words, with `exec` before the tool (or before its `env`)
                var scriptCommand = String(try #require(plan.script.split(separator: "\n").last))
                let exec = try #require(scriptCommand.range(of: "exec ", options: [], range: nil))
                scriptCommand.removeSubrange(exec)
                #expect(previewCommand == scriptCommand, "\(tool) \(account ?? "-")")
            }
        }
        #expect(try plan(.codex).preview.contains(unset))
    }
}

@Suite struct GeneratedFilesTests {
    private func mode(_ url: URL) throws -> Int {
        try (FileManager.default.attributesOfItem(atPath: url.path)[.posixPermissions] as? Int) ?? -1
    }

    @Test func scriptsAreOwnerOnlyAndKeyFree() throws {
        for tool in Tool.allCases {
            let plan = try plan(tool)
            try plan.writeFiles()
            #expect(try mode(plan.paths.generated) == 0o700)
            #expect(try mode(plan.scriptURL) == 0o700)
            #expect(try String(contentsOf: plan.scriptURL, encoding: .utf8) == plan.script)
            let files = try FileManager.default.contentsOfDirectory(at: plan.paths.generated, includingPropertiesForKeys: nil)
            for file in files {
                #expect(!(try String(contentsOf: file, encoding: .utf8)).contains(secret))
            }
            #expect(files.count == (tool == .claude ? 2 : 1))
        }
    }

    @Test func codexHomeIsPrivateWithAnEmptyConfigLeftToCodex() throws {
        let plan = try plan(.codex)
        try plan.writeFiles(script: false)
        let config = plan.paths.codexHome.appending(path: "config.toml")
        #expect(try mode(plan.paths.codexHome) == 0o700)
        #expect(try Data(contentsOf: config).isEmpty)

        let trusted = "[projects.\"/tmp\"]\ntrust_level = \"trusted\"\n"   // what Codex writes there
        try Data(trusted.utf8).write(to: config)
        try plan.writeFiles()
        #expect(try String(contentsOf: config, encoding: .utf8) == trusted)
    }

    @Test func everyLaunchGetsItsOwnScriptAndOnlyTheNewestAreKept() throws {
        let root = try temporaryDirectory()
        var written: [URL] = []
        for index in 0..<13 {
            let plan = try plan(.codex, root: root)
            try plan.writeFiles()
            // mtimes one second apart, so "newest" does not depend on timer resolution
            try FileManager.default.setAttributes([.modificationDate: Date(timeIntervalSince1970: TimeInterval(1_000 + index))],
                                                  ofItemAtPath: plan.scriptURL.path)
            written.append(plan.scriptURL)
        }
        #expect(Set(written).count == 13)
        let left = try FileManager.default.contentsOfDirectory(at: root.appending(path: "generated"), includingPropertiesForKeys: nil)
            .filter { $0.pathExtension == "command" }
        #expect(left.count == LaunchPlan.keptScripts)
        #expect(Set(left.map(\.lastPathComponent)) == Set(written.suffix(LaunchPlan.keptScripts).map(\.lastPathComponent)))
    }

    @Test func differentIdsNeverShareFiles() throws {
        let base = try plan(.claude)
        let stems = ["a/b", "a b", "a-b", "", "é"].map { id -> String in
            var preset = base.preset
            preset.id = id
            return LaunchPlan(preset: preset, directory: "/", paths: base.paths).stem
        }
        #expect(Set(stems).count == stems.count)
        #expect(stems[2] == "a-b")
        #expect(stems.allSatisfy { $0.unicodeScalars.allSatisfy { $0.isASCII } })
    }

    @Test func scriptAndPreviewAreValidShell() throws {
        for tool in Tool.allCases {
            let plan = try plan(tool, directory: "/tmp/it's here", extra: "--flag 'two words'")
            try plan.writeFiles()
            for arguments in [["/bin/bash", "-n", plan.scriptURL.path], ["/bin/bash", "-n", "-c", plan.preview],
                              ["/bin/zsh", "-n", "-c", plan.preview]] {
                let shell = Process()
                shell.executableURL = URL(fileURLWithPath: arguments[0])
                shell.arguments = Array(arguments.dropFirst())
                try shell.run()
                shell.waitUntilExit()
                #expect(shell.terminationStatus == 0, "\(arguments.prefix(2)) for \(tool)")
            }
        }
    }
}

@Suite struct AccountModeTests {
    private func plan(_ tool: Tool, account: String?, model: String = "", root: URL) -> LaunchPlan {
        let preset = Preset(id: "acct", name: "A", tool: tool, url: "", keyFile: nil, model: model, contextTokens: 200_000,
                            extraArgs: "", mode: .account, account: account)
        return LaunchPlan(preset: preset, directory: "/tmp", paths: LauncherPaths(root: root, warpTabConfigs: root))
    }

    private let claudeUnset = "env -u ANTHROPIC_BASE_URL -u ANTHROPIC_API_KEY -u ANTHROPIC_AUTH_TOKEN "
        + "-u CLAUDE_CODE_USE_BEDROCK -u CLAUDE_CODE_USE_VERTEX -u CLAUDE_CODE_USE_FOUNDRY"

    @Test func claudeDefaultAccountRunsWithItsConfigDirUnset() throws {
        let plan = plan(.claude, account: nil, model: "opus", root: try temporaryDirectory())
        let command = try #require(plan.script.split(separator: "\n").last)
        #expect(command == "exec env -u CLAUDE_CONFIG_DIR -u ANTHROPIC_BASE_URL -u ANTHROPIC_API_KEY -u ANTHROPIC_AUTH_TOKEN "
                + "-u CLAUDE_CODE_USE_BEDROCK -u CLAUDE_CODE_USE_VERTEX -u CLAUDE_CODE_USE_FOUNDRY claude --model opus")
        #expect(plan.accountDirectory == nil)
        #expect(!plan.script.contains("--bare") && !plan.script.contains("--settings") && !plan.script.contains("[ -r"))
    }

    @Test func claudeSeparateAccountGetsAnAbsoluteConfigDir() throws {
        let root = try temporaryDirectory()
        let plan = plan(.claude, account: "Lavoro Clienti", root: root)
        let directory = root.appending(path: "accounts/claude/lavoro-clienti").standardizedFileURL.path
        #expect(plan.accountDirectory == directory)
        let command = try #require(plan.script.split(separator: "\n").last)
        #expect(command == "CLAUDE_CONFIG_DIR=\(Shell.quote(directory)) exec \(claudeUnset) claude")
        #expect(!command.contains("-u CLAUDE_CONFIG_DIR"))
    }

    @Test func codexDefaultAccountRunsWithCodexHomeUnset() throws {
        let plan = plan(.codex, account: nil, model: "gpt-5.5", root: try temporaryDirectory())
        #expect(plan.script.hasSuffix("\nexec env -u CODEX_HOME codex -m gpt-5.5\n"))
        #expect(plan.preview == "cd /tmp && \\\nenv -u CODEX_HOME codex \\\n  -m gpt-5.5")
    }

    @Test func codexSeparateAccountGetsItsOwnHome() throws {
        let root = try temporaryDirectory()
        let plan = plan(.codex, account: "personale", root: root)
        let directory = root.appending(path: "accounts/codex/personale").standardizedFileURL.path
        #expect(plan.script.hasSuffix("\nCODEX_HOME=\(Shell.quote(directory)) exec codex\n"))
    }

    @Test func accountFoldersAreAbsolutePrivateAndSpelledOneWay() throws {
        let root = try temporaryDirectory()
        let paths = LauncherPaths(root: root.appending(path: "x/../hangar/"), warpTabConfigs: root)
        let directory = paths.accountDirectory(.claude, name: "Lavoro")
        #expect(directory == root.appending(path: "hangar/accounts/claude/lavoro").standardizedFileURL.path)
        #expect(!directory.contains("~") && !directory.hasSuffix("/") && !directory.contains("/../") && directory.hasPrefix("/"))
        #expect(paths.accountDirectory(.claude, name: " lavoro ") == directory)          // same login
        #expect(paths.accountDirectory(.codex, name: "Lavoro") != directory)              // per tool

        let plan = LaunchPlan(preset: Preset(id: "a", name: "A", tool: .claude, url: "", keyFile: nil, model: "",
                                             contextTokens: 1, extraArgs: "", mode: .account, account: "Lavoro"),
                              directory: "/tmp", paths: paths)
        try plan.writeFiles()
        for folder in [paths.accounts.path, paths.accounts.appending(path: "claude").path, directory] {
            #expect(try (FileManager.default.attributesOfItem(atPath: folder)[.posixPermissions] as? Int) == 0o700)
        }
        #expect(!FileManager.default.fileExists(atPath: plan.settingsURL.path))          // no server settings
    }

    @Test func slugsKeepLettersAndDigits() {
