let secret = "sk-test-SECRET-never-in-files"

/// A plan on a throwaway folder, with a key file holding a fake secret.
func plan(_ tool: Tool, directory: String = "/tmp/work dir", model: String = "qwen3-coder-30b",
          extra: String = "", root: URL? = nil) throws -> LaunchPlan {
    let root = try root ?? temporaryDirectory()
    let key = root.appending(path: "key dir/api-key")
    try FileManager.default.createDirectory(at: key.deletingLastPathComponent(), withIntermediateDirectories: true)
    try Data(secret.utf8).write(to: key)
    let preset = Preset(id: "my preset/1", name: "P", tool: tool, url: "https://gpu.example.com/",
                        keyFile: key.path, model: model, contextTokens: 131_072, extraArgs: extra)
    return LaunchPlan(preset: preset, directory: directory,
                      paths: LauncherPaths(root: root, warpTabConfigs: root.appending(path: "warp")))
}

/// The default LM Studio preset (no auth) with a model picked.
func lmStudioPlan(_ tool: Tool) throws -> LaunchPlan {
    let root = try temporaryDirectory()
    let config = LauncherConfig.defaults
    var preset = try #require(config.presets.first { $0.mode == .server && $0.tool == tool })
    preset.model = "qwen3-coder-30b"
    return LaunchPlan(preset: preset, directory: "/tmp",
                      paths: LauncherPaths(root: root, warpTabConfigs: root.appending(path: "warp")))
}

